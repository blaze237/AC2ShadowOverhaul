# Generates default-implementation C++ classes for a few d3d9 interfaces from mingw's d3d9.h.
import re, sys
src = open(sys.argv[1]).read()
out = ["// generated by gen_mock.py", "#pragma once", "#include <d3d9.h>"]
for name in ["IDirect3D9", "IDirect3DDevice9", "IDirect3DSurface9", "IDirect3DTexture9", "IDirect3DPixelShader9"]:
    m = re.search(r"#define INTERFACE %s\nDECLARE_INTERFACE_IID_\(%s,.*?\n\{(.*?)\n\};" % (name, name), src, re.S)
    body = m.group(1)
    out.append("struct Gen_%s : %s {" % (name, name))
    for decl in re.findall(r"STDMETHOD_?\(.*?\)\(.*?\)\s*PURE;", body, re.S):
        decl = " ".join(decl.split())
        rm = re.match(r"STDMETHOD(_?)\((.*?)\)\((.*)\) PURE;", decl)
        under, head, args = rm.groups()
        args = re.sub(r"^THIS_?\s*", "", args)
        if under:
            rtype, mname = [x.strip() for x in head.split(",", 1)]
            ret = "{}" if rtype == "void" else "{ return (%s)0; }" % rtype
            out.append("  STDMETHOD_(%s,%s)(%s) override %s" % (rtype, mname, args, ret))
        else:
            out.append("  STDMETHOD(%s)(%s) override { return S_OK; }" % (head.strip(), args))
    out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
